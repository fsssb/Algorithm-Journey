/**
 * @file 0062_Unique_Paths.cpp
 * @brief 62. 不同路径
 * @link https://leetcode.cn/problems/unique-paths/
 *
 * @algorithm 1. 经典二维动态规划 | 2. 空间优化一维动态规划 | 3. 数学组合数(边乘边除)
 * @time_complexity 
 *   - 方法 1 (2D DP)：O(M * N) - 双重循环遍历整个网格
 *   - 方法 2 (1D DP)：O(M * N) - 双重循环，但消除了冗余维度
 *   - 方法 3 (数学组合数)：O(min(M, N)) - 仅需进行 min(M-1, N-1) 次简单的乘除运算
 * @space_complexity 
 *   - 方法 1 (2D DP)：O(M * N) - 需要一个 M * N 大小的二维状态矩阵
 *   - 方法 2 (1D DP)：O(N) - 仅需一个大小为 N 的一维状态数组
 *   - 方法 3 (数学组合数)：O(1) - 仅需几个常数级别的辅助变量
 *
 * @note 核心思路：
 * 本文件提供了三种解决《不同路径》的完整算法实现：
 * 1. 2D DP：使用 dp[i][j] = dp[i-1][j] + dp[i][j-1]，修正了边界初始化（设为1而非索引）以及内层循环控制变量（j < n）防止越界。
 * 2. 1D DP：基于 2D DP 的滚动数组优化。仅需大小为 N 的一维数组 dp。内层循环从 j=1 开始：dp[j] += dp[j-1]。
 *    - 极佳设计：第一列 dp[0] 在初始化为 1 后，在每行计算中不参与更新，无声地保持其恒为 1 的物理状态作为递推左侧基石。
 * 3. 数学组合数：总共需要走 m + n - 2 步，其中向下 m - 1 步，转换为求组合数 C(m + n - 2, min(m - 1, n - 1))。
 *    - 防溢出机制：采用“边乘边除”递推算法，保证中间累乘项必能被当前步 i 整除，在 long long 辅助下彻底杜绝中途整型溢出。
 */

#include <vector>
#include <algorithm>

using namespace std;

class Solution {
public:
    // 主调用入口：默认调用运行速度最快、最优雅的数学组合数方法
    int uniquePaths(int m, int n) {
        return uniquePaths_Math(m, n);
    }

    // =========================================================================
    // 写法一：经典二维动态规划 (Bug 修复安全版)
    // =========================================================================
    int uniquePaths_2D(int m, int n) {
        // 创建二维 dp 数组并默认初始化为 0
        vector<vector<int>> dp(m, vector<int>(n, 0));
        
        // 安全初始化：机器人只能一路往下，所以第一列的所有走法都是 1 种（而非行索引 i）
        for (int i = 0; i < m; ++i) {
            dp[i][0] = 1;
        }

        // 安全初始化：机器人只能一路往右，所以第一行的所有走法都是 1 种
        for (int i = 0; i < n; ++i) {
            dp[0][i] = 1;
        }

        // 二维递推
        for (int i = 1; i < m; ++i) {
            // 🚀 安全加固：内层循环条件修改为 j < n（原笔误为 i < n，会导致 j 无限增加从而数组越界崩溃）
            for (int j = 1; j < n; ++j) {
                dp[i][j] = dp[i - 1][j] + dp[i][j - 1];
            }
        }

        return dp[m - 1][n - 1];
    }

    // =========================================================================
    // 写法二：一维滚动数组动态规划 (空间优化极简版)
    // =========================================================================
    int uniquePaths_1D(int m, int n) {
        // 创建大小为 n 的一维数组，默认全部初始化为 1
        // 这完美承载了“第一行全部为 1”的初始化
        vector<int> dp(n, 1);

        // 外层遍历行，内层遍历列
        for (int i = 1; i < m; ++i) {
            // 🚀 优雅设计：j 从 1 开始遍历。
            // 代表第一列的 dp[0] 不参与更新，从而在每行都永久、安静地保持其初始值 1，作为递推的左侧基石
            for (int j = 1; j < n; ++j) {
                // 当前 dp[j] (新值) = 上一行的 dp[j] (旧值) + 正左方刚才算好的新值 dp[j-1]
                dp[j] += dp[j - 1];
            }
        }

        return dp[n - 1];
    }

    // =========================================================================
    // 写法三：数学组合数 (O(min(M, N)) 极致性能版)
    // =========================================================================
    int uniquePaths_Math(int m, int n) {
        int N = m + n - 2;
        int K = min(m - 1, n - 1);

        long long res = 1;
        // 边乘边除计算组合数 C(N, K)，分子分母同步推进，完全避免中间计算过程中的整型溢出
        for (int i = 1; i <= K; ++i) {
            res = res * (N - K + i) / i;
        }

        return static_cast<int>(res);
    }
};

